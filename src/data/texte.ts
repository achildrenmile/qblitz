// Helper to format time duration
export const formatZeit = (sekunden: number): string => {
  if (sekunden < 60) {
    return `${sekunden} ${sekunden === 1 ? texte.common.sekunde : texte.common.sekunden}`
  }
  const minuten = Math.floor(sekunden / 60)
  const restSekunden = sekunden % 60
  if (restSekunden === 0) {
    return `${minuten} ${minuten === 1 ? texte.common.minute : texte.common.minuten}`
  }
  return `${minuten}:${restSekunden.toString().padStart(2, '0')} ${texte.common.minuten}`
}

// Helper to format streak duration
export const formatStreak = (tage: number): string => {
  return `${tage} ${tage === 1 ? texte.common.tag : texte.common.tage}`
}

// Helper to format percentage
export const formatProzent = (wert: number, gesamt: number): string => {
  if (gesamt === 0) return '0%'
  return `${Math.round((wert / gesamt) * 100)}%`
}
